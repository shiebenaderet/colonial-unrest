/* Builds readings.html (all nine readings at every level, plus the Level 0
   translations) and canvas/unrest-readings.pdf from the live text in
   index.html, so the printed readings can never drift from the app.
   Run after editing any reading:   node tools/build-readings.js
   Needs Playwright with Chromium (used to read the app's data and to print). */
const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const esc = s => String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');
const paras = html => html.trim().split(/\n\s*\n/).map(p => `<p>${p.trim().replace(/\n/g,' ')}</p>`).join('\n');

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.goto('file://' + path.join(ROOT, 'index.html'));
  await page.waitForTimeout(400);
  const d = await page.evaluate(() => ({
    langs: L0_LANGS, tags: LANG_TAG,
    levels: LEVELS.map(l => ({ key: l.key, label: l.label })),
    scale: SCALE.map(s => ({ n: s.n, name: s.name, desc: s.desc })),
    events: EVENTS.map(e => ({ id: e.id, title: e.title, year: e.year, side: SIDE[e.side].en,
      text: { l0: textFor(e, 'l0', 'en'), ss: textFor(e, 'ss'), core: textFor(e, 'core'), adv: textFor(e, 'adv') },
      l0: Object.fromEntries(L0_LANGS.map(([k]) => [k, textFor(e, 'l0', k)])),
      terms: (GLOSSARY[e.id] || []).map(g => ({ t: g.t, d: g.d, u: !!g.u })) }))
  }));

  const LEVEL_NOTE = { l0: 'Level 0: short sentences, key words explained in the text',
    ss: 'Level 1: below grade, plain words', core: 'Level 2: at grade', adv: 'Level 3: above grade, with primary sources' };
  const order = ['l0', 'ss', 'core', 'adv'];

  let body = `
<header class="top">
  <h1>Unrest in the Colonies · The readings</h1>
  <p class="sub">Nine events on the road to the American Revolution, 1763 to 1775, at four reading levels. The same facts at every level. These are the readings from <a href="https://unrest.mrbsocialstudies.org">unrest.mrbsocialstudies.org</a>, printed.</p>
  <button type="button" class="print no-print" onclick="window.print()">Print or save as PDF</button>
  <nav class="toc no-print"><strong>Jump to:</strong> ${d.events.map(e => `<a href="#ev-${e.id}">${esc(e.title)}</a>`).join(' · ')} · ${d.langs.filter(([k]) => k !== 'en').map(([k, l]) => `<a href="#lang-${k}">Level 0 in ${esc(l)}</a>`).join(' · ')}</nav>
  <div class="scale"><strong>The unrest scale students use:</strong> ${d.scale.map(s => `${s.n} ${esc(s.name)}`).join(' · ')}.<br>Each number means how angry people were and how many of them, from 1 (${esc(d.scale[0].desc)}) to 8 (${esc(d.scale[7].desc)}).</div>
</header>`;

  d.events.forEach((e, i) => {
    body += `\n<section class="event" id="ev-${e.id}">
  <h2>${i + 1}. ${esc(e.title)} <span class="year">${e.year}</span> <span class="side">${esc(e.side)}</span></h2>`;
    for (const k of order) {
      body += `\n  <div class="level"><h3>${esc(LEVEL_NOTE[k])}</h3>\n${paras(e.text[k])}\n  </div>`;
    }
    if (e.terms.length) body += `\n  <div class="terms"><h3>Key terms</h3><ul>${e.terms.map(t => `<li><strong>${esc(t.t)}</strong>: ${esc(t.d)}${t.u ? ' <em class="unit">(Unit 2 word)</em>' : ''}</li>`).join('')}</ul></div>`;
    body += `\n</section>`;
  });

  for (const [k, label] of d.langs) {
    if (k === 'en') continue;
    body += `\n<section class="lang" id="lang-${k}" lang="${d.tags[k]}" translate="no">
  <h2 class="lang-h">Level 0 in ${esc(label)}</h2>
  <p class="sub" lang="en">The Level 0 readings, translated. Key unit terms keep the English word beside the translation.</p>`;
    d.events.forEach((e, i) => { body += `\n  <h3>${i + 1}. ${esc(e.title)} <span class="year">${e.year}</span></h3>\n${paras(e.l0[k])}`; });
    body += `\n</section>`;
  }

  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Unrest in the Colonies · The readings</title>
<!-- GENERATED by tools/build-readings.js from index.html. Do not edit by hand:
     edit the reading in index.html and rerun the script. -->
<link rel="stylesheet" href="fonts/atkinson.css">
<style>
  :root{--ink:#1a1a1a;--muted:#4a4a4a;--rule:#bdbdbd;--accent:#7a2a28;--tint:#f6e7e4}
  *{box-sizing:border-box}
  body{margin:0;background:#f4f2ec;color:var(--ink);font-family:'Atkinson Hyperlegible Next',system-ui,sans-serif;font-size:12pt;line-height:1.5}
  .page{max-width:8.5in;margin:0 auto;background:#fff;padding:.6in .7in}
  h1{font-size:22pt;margin:0 0 .1in;line-height:1.2}
  h2{font-size:17pt;margin:0 0 .15in;padding-bottom:.06in;border-bottom:2px solid var(--accent);line-height:1.25}
  h3{font-size:11pt;margin:.2in 0 .06in;color:var(--accent);text-transform:uppercase;letter-spacing:.06em}
  p{margin:0 0 .1in;max-width:70ch}
  a{color:var(--accent)}
  .sub{color:var(--muted);font-size:11pt}
  .top{margin-bottom:.4in}
  .toc{font-size:10pt;line-height:1.8;margin:.1in 0}
  .scale{background:var(--tint);border-left:4px solid var(--accent);padding:.1in .15in;font-size:10.5pt;margin-top:.15in}
  .print{font:inherit;font-weight:700;background:var(--accent);color:#fff;border:0;border-radius:8px;padding:.1in .25in;cursor:pointer;margin:.1in 0}
  .event,.lang{break-before:page;padding-top:.1in}
  .year{font-weight:400;color:var(--muted);font-size:13pt}
  .side{display:inline-block;font-size:9.5pt;font-weight:700;color:var(--accent);border:1.5px solid var(--accent);border-radius:999px;padding:0 .12in;vertical-align:middle;margin-left:.08in}
  .level{break-inside:avoid-page}
  .terms{margin-top:.2in;background:var(--tint);padding:.08in .15in;border-radius:6px;font-size:10.5pt}
  .terms ul{margin:0;padding-left:1.2em} .terms li{margin:0 0 .03in} .unit{color:var(--accent);font-style:normal;font-weight:700}
  .lang h3{text-transform:none;letter-spacing:0;font-size:13pt;color:var(--ink);margin-top:.25in}
  @media print{ @page{size:letter;margin:.6in .7in} body{background:#fff} .page{max-width:none;padding:0;margin:0} .no-print{display:none} }
</style>
</head>
<body>
<div class="page">
${body}
<footer class="sub" style="margin-top:.4in;border-top:1px solid var(--rule);padding-top:.1in">Mr. Benaderet · 8th Grade American Studies · unrest.mrbsocialstudies.org</footer>
</div>
</body>
</html>
`;
  fs.writeFileSync(path.join(ROOT, 'readings.html'), html);

  const out = await browser.newPage();
  await out.goto('file://' + path.join(ROOT, 'readings.html'));
  await out.waitForTimeout(600);
  await out.emulateMedia({ media: 'print' });
  await out.pdf({ path: path.join(ROOT, 'canvas', 'unrest-readings.pdf'), format: 'Letter', printBackground: true, margin: { top: '0.6in', bottom: '0.6in', left: '0.7in', right: '0.7in' } });
  await browser.close();
  console.log('wrote readings.html and canvas/unrest-readings.pdf:', d.events.length, 'events,', d.langs.length - 1, 'translations');
})().catch(e => { console.error(e); process.exit(1); });
